def response(status=401, body=b"Unauthorized", content_type="text/plain"):
    return {"status": status, "headers": {"Content-Type": content_type}, "body": body,
            "final_url": "http://127.0.0.1/task", "reason": "", "title": ""}


def challenge(status=401):
    return response(status, b'<html><script>document.cookie="challenge=ready; path=/";</script></html>', "text/html")


def request(method="GET", navigation=True, url="http://127.0.0.1/task", body=b""):
    return {"method": method, "url": url, "headers": ["Accept: text/html" if navigation else "Accept: application/json"],
            "body": body, "isolate_cookies": False}


def packet(status=401, body="Unauthorized", **kwargs):
    values = dict(frameId="main", resourceType="Document", url="http://127.0.0.1/task", method="GET",
                  _raw_request={}, response=types.SimpleNamespace(status=status, statusText="Unauthorized",
                      headers={"Content-Type": "text/plain"}, raw_body=body, _is_base64_body=False))
    values.update(kwargs)
    return types.SimpleNamespace(**values)


class ChallengeUnitTest(unittest.TestCase):
    def test_auxiliary_host_matching_is_exact_and_not_based_on_path_text(self):
        auxiliary = 'http://me.kis.v2.scr.kaspersky-labs.com/token/to/wsm.sessionActivated'
        self.assertTrue(bridge.is_auxiliary_browser_url(auxiliary))
        self.assertFalse(bridge.is_auxiliary_browser_url('https://example.test/?src=' + auxiliary))
        self.assertFalse(bridge.is_auxiliary_browser_url('https://scr.kaspersky-labs.com.example.test/main.js'))
        import re
        self.assertIsNone(re.search(bridge.OBSERVED_HTTP_URL_PATTERN, auxiliary))
        self.assertIsNotNone(re.search(bridge.OBSERVED_HTTP_URL_PATTERN, 'http://127.0.0.1/task'))

    def test_auxiliary_injected_js_is_not_challenge_evidence_and_body_stays_unchanged(self):
        body = (b'<html>401 Unauthorized<script src="//me.kis.v2.scr.kaspersky-labs.com/id/main.js">'
                b'document.cookie="aux=1";</script></html>')
        raw = response(401, body, 'text/html')
        self.assertFalse(bridge.is_challenge_response(raw))
        self.assertEqual(body, raw['body'])
        self.assertNotIn('document.cookie', bridge.challenge_analysis_html(body.decode()))

    def test_own_challenge_script_survives_auxiliary_script_filter(self):
        raw = challenge(412)
        raw['body'] += b'<script src="https://me.kis.v2.scr.kaspersky-labs.com/id/main.js"></script>'
        self.assertTrue(bridge.is_challenge_response(raw))

    def test_status_alone_does_not_trigger_replay(self):
        for status in (200, 401, 403, 412, 413, 429, 503):
            with self.subTest(status=status):
                self.assertFalse(bridge.is_challenge_response(response(status)))
                self.assertFalse(bridge.is_challenge_response(response(status, b'<html>Access denied</html>', 'text/html')))

    def test_cookie_scripts_are_challenges_at_401_412_413(self):
        for status in (401, 412, 413):
            self.assertTrue(bridge.is_challenge_response(challenge(status)))

    def test_json_containing_script_example_is_not_a_challenge(self):
        self.assertFalse(bridge.is_challenge_response(response(401, challenge()['body'], 'application/json')))

    def test_opaque_412_bootstrap_does_not_need_a_literal_document_cookie(self):
        raw = b'<html><meta content="seed"><script>window.$_ts={seed:1};</script><script src="/bootstrap.js"></script></html>'
        self.assertTrue(bridge.is_challenge_response(response(412, raw, 'text/html')))
        # An ordinary successful application page is not replayed based on this marker alone.
        self.assertFalse(bridge.is_challenge_response(response(200, raw, 'text/html')))

    def test_raw_json_is_not_reserialized(self):
        raw = '{ "n": 1, "n": 2, "ok": false }'
        result = bridge.network_packet_result(packet(412, raw))
        self.assertEqual(raw.encode(), result['body'])
        self.assertEqual(412, result['status'])

    def test_base64_response_bytes_are_preserved(self):
        p = packet(413)
        p.response._is_base64_body = True
        p.response.raw_body = base64.b64encode(b'\x00\xff\x80').decode()
        self.assertEqual(b'\x00\xff\x80', bridge.network_packet_result(p)['body'])

    def test_missing_body_is_explicit_never_substituted_with_dom(self):
        result = bridge.network_packet_result(packet(401, None))
        self.assertEqual(401, result['status'])
        self.assertEqual(b'', result['body'])
        self.assertEqual('true', result['headers']['X-OST-Body-Unavailable'])

    def test_unrelated_frames_and_assets_are_not_selected(self):
        tab = Mock()
        with patch.object(bridge, 'resolve_live_tab', return_value=tab):
            tab.run_cdp.return_value = {'frameTree': {'frame': {'id': 'main'}}}
            capture = bridge.RequestNetworkCapture(tab, request())
        self.assertTrue(capture.accepts(packet()))
        self.assertFalse(capture.accepts(packet(frameId='iframe')))
        self.assertFalse(capture.accepts(packet(resourceType='Image')))
        self.assertFalse(capture.accepts(packet(resourceType='Fetch', url='http://127.0.0.1/analytics')))
        self.assertFalse(capture.accepts(packet(url='chrome-error://chromewebdata/')))
        self.assertFalse(capture.accepts(packet(url='https://me.kis.v2.scr.kaspersky-labs.com/main.js')))

    def test_post_does_not_take_an_unrelated_get_as_its_response(self):
        tab = Mock()
        tab.run_cdp.return_value = {'frameTree': {'frame': {'id': 'main'}}}
        with patch.object(bridge, 'resolve_live_tab', return_value=tab):
            capture = bridge.RequestNetworkCapture(tab, request('POST'))
        self.assertFalse(capture.accepts(packet()))
        self.assertTrue(capture.accepts(packet(method='POST')))
        self.assertTrue(capture.accepts(packet(_raw_request={'redirectResponse': {'status': 303}})))

    def test_httponly_cookie_change_is_detected_but_expiry_is_ignored(self):
        tab = Mock()
        cookie = {'domain': '127.0.0.1', 'path': '/', 'name': 'token', 'value': 'a', 'httpOnly': True, 'expires': 1}
        tab.run_cdp.return_value = {'cookies': [cookie]}
        with patch.object(bridge, 'resolve_live_tab', return_value=tab):
            first = bridge.challenge_cookie_state(tab, request())
            cookie['expires'] = 2
            self.assertEqual(first, bridge.challenge_cookie_state(tab, request()))
            cookie['value'] = 'b'
            self.assertNotEqual(first, bridge.challenge_cookie_state(tab, request()))
        tab.run_cdp.assert_called_with('Network.getCookies', urls=['http://127.0.0.1/task'])

    def test_plain_error_does_not_render_or_replay(self):
        raw = response()
        with patch.object(bridge, 'load_challenge_page') as render, patch.object(bridge, 'send_browser_attempt') as send:
            self.assertIs(raw, bridge.finish_browser_challenge(Mock(), request(), raw, Mock(), (), .01, False))
            render.assert_not_called()
            send.assert_not_called()

    def test_cookie_progress_replays_once_and_returns_second_raw_error(self):
        raw = response(401, b'second 401')
        capture = Mock()
        capture.failed_request = False
        capture.wait.return_value = None
        capture.has_pending_request.return_value = False
        with patch.object(bridge, 'load_challenge_page'), patch.object(bridge, 'challenge_cookie_state', return_value=('new',)), \
             patch.object(bridge, 'COOKIE_SETTLE_SECONDS', 0), patch.object(bridge, 'send_browser_attempt', return_value=raw) as send:
            result = bridge.finish_browser_challenge(Mock(), request('POST', False, body=b'a=1'), challenge(), capture, (), .2, False)
        self.assertIs(raw, result)
        self.assertEqual(1, send.call_count)
        self.assertEqual(b'a=1', send.call_args.args[1]['body'])
        self.assertFalse(send.call_args.args[-1])

    def test_no_cookie_progress_never_replays_post(self):
        initial = challenge(413)
        capture = Mock()
        capture.failed_request = False
        capture.wait.side_effect = lambda _: time.sleep(.001)
        with patch.object(bridge, 'load_challenge_page'), patch.object(bridge, 'challenge_cookie_state', return_value=()), \
             patch.object(bridge, 'submit_hidden_form_intermediate', return_value=False), \
             patch.object(bridge, 'send_browser_attempt') as send:
            self.assertIs(initial, bridge.finish_browser_challenge(Mock(), request('POST'), initial, capture, (), .02, False))
        send.assert_not_called()

    def test_page_already_replayed_does_not_get_an_extra_bridge_replay(self):
        raw = response(200, b'final')
        capture = Mock()
        capture.failed_request = False
        capture.wait.return_value = raw
        with patch.object(bridge, 'send_browser_attempt') as send:
            self.assertIs(raw, bridge.finish_browser_challenge(Mock(), request(), challenge(), capture, (), .1, True))
        send.assert_not_called()

    def test_self_reloading_challenge_is_bounded(self):
        raw = challenge()
        capture = Mock()
        capture.failed_request = False
        capture.wait.return_value = raw
        with patch.object(bridge, 'challenge_cookie_state', return_value=()), patch.object(bridge, 'send_browser_attempt') as send:
            self.assertIs(raw, bridge.finish_browser_challenge(Mock(), request(), raw, capture, (), .1, True))
        self.assertEqual(2, capture.wait.call_count)
        send.assert_not_called()

    def test_completed_packet_between_wait_and_idle_check_is_not_lost(self):
        tab = Mock()
        tab.run_cdp.return_value = {"frameTree": {"frame": {"id": "main"}}}
        with patch.object(bridge, 'resolve_live_tab', return_value=tab):
            capture = bridge.RequestNetworkCapture(tab, request('POST'))
        capture.started = True
        tab.listen.wait_silent.return_value = True
        tab.listen.wait.return_value = packet(status=200, body='final', method='POST', resourceType='Fetch')
        self.assertTrue(capture.has_pending_request())
        self.assertTrue(capture.has_pending_request())
        self.assertEqual(1, tab.listen.wait.call_count)
        self.assertEqual(b'final', capture.wait(.01)['body'])
        self.assertIsNone(capture.buffered_result)

    def test_completed_failed_packet_prevents_replay_at_idle_boundary(self):
        tab = Mock()
        tab.run_cdp.return_value = {"frameTree": {"frame": {"id": "main"}}}
        with patch.object(bridge, 'resolve_live_tab', return_value=tab):
            capture = bridge.RequestNetworkCapture(tab, request('POST'))
        capture.started = True
        tab.listen.wait_silent.return_value = True
        tab.listen.wait.side_effect = [packet(status=0, body='', method='POST', resourceType='Fetch', is_failed=True), None]
        self.assertTrue(capture.has_pending_request())
        self.assertTrue(capture.failed_request)

    def test_cookie_change_does_not_replay_while_page_request_is_in_flight(self):
        capture = Mock()
        capture.failed_request = False
        capture.wait.side_effect = lambda _: time.sleep(.001)
        capture.has_pending_request.return_value = True
        initial = challenge()
        with patch.object(bridge, 'challenge_cookie_state', return_value=('new',)), \
             patch.object(bridge, 'COOKIE_SETTLE_SECONDS', 0), patch.object(bridge, 'send_browser_attempt') as send:
            self.assertIs(initial, bridge.finish_browser_challenge(Mock(), request('POST'), initial, capture, (), .02, True))
        send.assert_not_called()

    def test_failed_automatic_post_is_not_replayed(self):
        capture = Mock()
        capture.wait.return_value = None
        capture.failed_request = True
        with patch.object(bridge, 'send_browser_attempt') as send:
            result = bridge.finish_browser_challenge(Mock(), request('POST'), challenge(412), capture, (), .1, True)
        self.assertEqual(412, result['status'])
        self.assertEqual('response-unavailable; not-retried', result['headers']['X-OST-Challenge-Replay'])
        send.assert_not_called()


@unittest.skipUnless(os.environ.get('OST_BROWSER_INTEGRATION') == '1', 'Opt-in local headless browser tests')
class BrowserLoopbackTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
        import tempfile
        cls.events = []
        cls.blocked_started = threading.Event()
        cls.release_blocked = threading.Event()

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass

            def do_GET(self):
                self.serve()

            def do_POST(self):
                self.serve()

            def serve(self):
                body = self.rfile.read(int(self.headers.get('Content-Length', '0')))
                cls.events.append((self.command, self.path, body))
                status = 200
                headers = {}
                content = b'<html><body>context</body></html>'
                if self.path == '/hold-browser':
                    cls.blocked_started.set()
                    cls.release_blocked.wait(10)
                    content = self.headers.get('Cookie', '').encode()
                elif self.path == '/cookie-echo':
                    content = self.headers.get('Cookie', '').encode()
                elif self.path.startswith('/plain/'):
                    status = int(self.path.rsplit('/', 1)[1])
                    content = b'original-error-' + str(status).encode()
                elif self.path == '/set-cookie':
                    headers['Set-Cookie'] = 'challenge=ready; Path=/; HttpOnly; SameSite=Lax'
                    content = b'cookie set'
                elif self.path.startswith('/challenge/'):
                    status = int(self.path.rsplit('/', 1)[1])
                    if 'challenge=ready' in self.headers.get('Cookie', ''):
                        content = b'{ "final": true, "status": 200 }'
                        status = 200
                        headers['Content-Type'] = 'application/json'
                    else:
                        content = b'<html><script>document.cookie="challenge=ready; path=/";</script></html>'
                elif self.path == '/httponly':
                    if 'challenge=ready' in self.headers.get('Cookie', ''):
                        content = b'HttpOnly-success'
                    else:
                        status = 412
                        content = b'<html><script>/* anti-bot challenge */ fetch("/set-cookie");</script></html>'
                elif self.path == '/twice':
                    status = 401
                    if 'challenge=ready' in self.headers.get('Cookie', ''):
                        content = b'final unauthorized only'
                    else:
                        content = b'<html><script>document.cookie="challenge=ready; path=/";</script></html>'
                elif self.path == '/auto':
                    if 'challenge=ready' in self.headers.get('Cookie', ''):
                        content = b'auto-final'
                    else:
                        status = 413
                        content = b'<html><script>document.cookie="challenge=ready; path=/"; location.reload();</script></html>'
                elif self.path == '/auth':
                    status = 401
                    headers['WWW-Authenticate'] = 'Basic realm="fixture"'
                    content = b'authentication required'
                elif self.path == '/slow-auto-post':
                    if 'challenge=ready' in self.headers.get('Cookie', ''):
                        time.sleep(1)
                        content = b'slow-post-final'
                    else:
                        status = 412
                        content = (b'<html><script>document.cookie="challenge=ready; path=/";'
                                   b'setTimeout(()=>fetch("/slow-auto-post", {method:"POST", body:"a=1"}), 0);</script></html>')
                self.send_response(status)
                self.send_header('Content-Type', headers.pop('Content-Type', 'text/html; charset=UTF-8'))
                for key, value in headers.items():
                    self.send_header(key, value)
                self.send_header('Content-Length', str(len(content)))
                self.end_headers()
                try:
                    self.wfile.write(content)
                except (BrokenPipeError, ConnectionResetError):
                    pass

        cls.server = ThreadingHTTPServer(('127.0.0.1', 0), Handler)
        cls.server.daemon_threads = True
        cls.thread = threading.Thread(target=cls.server.serve_forever, daemon=True)
        cls.thread.start()
        cls.origin = f'http://127.0.0.1:{cls.server.server_port}'
        work = ROOT / 'target/browser-challenge-fixtures'
        work.mkdir(parents=True, exist_ok=True)
        cls.profile = tempfile.mkdtemp(prefix='profile-', dir=str(work))
        args = types.SimpleNamespace(user_data_path=cls.profile, load_static_resources=False,
                                     browser_type='edge', browser_path='', timeout_ms=12000)
        options = bridge.build_options(args, bridge.find_free_port())
        options.headless(True)
        cls.browser = bridge.Chromium(options)
        cls.tab = cls.browser.latest_tab

    @classmethod
    def tearDownClass(cls):
        cls.browser.quit()
        cls.server.shutdown()
        cls.server.server_close()
        cls.thread.join(3)

    def setUp(self):
        self.tab.get(self.origin + '/', retry=0, timeout=3)
        self.tab.run_cdp('Network.clearBrowserCookies')
        self.events.clear()

    def execute(self, path, method='GET', navigation=True, body=b''):
        req = request(method, navigation, self.origin + path, body)
        if method == 'POST':
            req['headers'].append('Content-Type: application/x-www-form-urlencoded')
        return bridge.execute_network_request(self.tab, req, 10, False)

    def count(self, path):
        return sum(event[1] == path for event in self.events)

    def test_independent_browser_profiles_run_concurrently_without_cookie_mix(self):
        from concurrent.futures import ThreadPoolExecutor
        import tempfile
        profile = tempfile.mkdtemp(prefix='parallel-profile-', dir=str(ROOT / 'target/browser-challenge-fixtures'))
        args = types.SimpleNamespace(user_data_path=profile, load_static_resources=False,
                                     browser_type='edge', browser_path='', timeout_ms=12000)
        options = bridge.build_options(args, bridge.find_free_port())
        options.headless(True)
        browser = bridge.Chromium(options)
        executor = ThreadPoolExecutor(max_workers=1)
        try:
            other = browser.latest_tab
            other.get(self.origin + '/', retry=0, timeout=3)
            self.tab.run_cdp('Network.setCookie', name='isolated', value='ordinary', url=self.origin)
            other.run_cdp('Network.setCookie', name='isolated', value='parameter', url=self.origin)
            self.blocked_started.clear()
            self.release_blocked.clear()
            pending = executor.submit(self.execute, '/hold-browser')
            self.assertTrue(self.blocked_started.wait(3))
            isolated_request = request('GET', True, self.origin + '/cookie-echo')
            result = bridge.execute_network_request(other, isolated_request, 5, False)
            self.assertEqual(b'isolated=parameter', result['body'])
            self.assertFalse(pending.done(), 'ordinary browser must still be waiting')
            self.release_blocked.set()
            self.assertEqual(b'isolated=ordinary', pending.result(timeout=5)['body'])
        finally:
            self.release_blocked.set()
            executor.shutdown(wait=True)
            browser.quit()

    def test_plain_errors_make_one_request_and_keep_original_body(self):
        for method in ('GET', 'POST'):
            for status in (401, 412, 413):
                with self.subTest(method=method, status=status):
                    self.events.clear()
                    path = '/plain/' + str(status)
                    result = self.execute(path, method, body=b'x=one' if method == 'POST' else b'')
                    self.assertEqual(status, result['status'])
                    self.assertEqual(b'original-error-' + str(status).encode(), result['body'])
                    self.assertEqual(1, self.count(path))

    def test_cookie_challenges_replay_original_get_or_post_once(self):
        for method in ('GET', 'POST'):
            for status in (401, 412, 413):
                with self.subTest(method=method, status=status):
                    self.tab.run_cdp('Network.clearBrowserCookies')
                    self.events.clear()
                    path = '/challenge/' + str(status)
                    body = b'item=one&item=two' if method == 'POST' else b''
                    result = self.execute(path, method, body=body)
                    self.assertEqual(200, result['status'])
                    self.assertEqual(b'{ "final": true, "status": 200 }', result['body'])
                    matched = [event for event in self.events if event[1] == path]
                    self.assertEqual([(method, path, body)] * 2, matched)

    def test_fetch_challenge_executes_script_and_preserves_post_body(self):
        result = self.execute('/challenge/412', 'POST', False, b'a=1&b=%2F')
        self.assertEqual(200, result['status'])
        matched = [event for event in self.events if event[1] == '/challenge/412']
        self.assertEqual([('POST', '/challenge/412', b'a=1&b=%2F')] * 2, matched)

    def test_httponly_cookie_challenge_ignores_auxiliary_fetch_response(self):
        result = self.execute('/httponly')
        self.assertEqual(200, result['status'])
        self.assertEqual(b'HttpOnly-success', result['body'])
        self.assertEqual(2, self.count('/httponly'))
        self.assertEqual(1, self.count('/set-cookie'))

    def test_two_consecutive_401s_return_only_last_response(self):
        result = self.execute('/twice')
        self.assertEqual(401, result['status'])
        self.assertEqual(b'final unauthorized only', result['body'])
        self.assertEqual(2, self.count('/twice'))

    def test_automatic_reload_does_not_add_third_request(self):
        result = self.execute('/auto')
        self.assertEqual(b'auto-final', result['body'])
        self.assertEqual(2, self.count('/auto'))

    def test_browser_auth_error_page_is_never_used_as_response_body(self):
        result = self.execute('/auth')
        self.assertEqual(401, result['status'])
        self.assertIn(result['body'], (b'authentication required', b''))
        self.assertEqual(1, self.count('/auth'))

    def test_script_post_in_flight_does_not_trigger_a_duplicate_post(self):
        result = self.execute('/slow-auto-post', 'POST', True, b'a=1')
        self.assertEqual(b'slow-post-final', result['body'])
        self.assertEqual(2, self.count('/slow-auto-post'))

    def test_script_post_from_injected_challenge_also_finishes_without_duplicate(self):
        result = self.execute('/slow-auto-post', 'POST', False, b'a=1')
        self.assertEqual(b'slow-post-final', result['body'])
        self.assertEqual(2, self.count('/slow-auto-post'))


